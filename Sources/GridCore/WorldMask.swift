    public static func isLand(lon: Double, lat: Double) -> Bool {
        land.contains { contains($0, lon, lat) } && !water.contains { contains($0, lon, lat) }
    }

    /// Even-odd ray casting.
    static func contains(_ poly: Polygon, _ x: Double, _ y: Double) -> Bool {
        var inside = false
        var j = poly.count - 1
        for i in 0..<poly.count {
            let (xi, yi) = poly[i], (xj, yj) = poly[j]
            if (yi > y) != (yj > y), x < (xj - xi) * (y - yi) / (yj - yi) + xi { inside.toggle() }
            j = i
        }
        return inside
    }

    /// An evenly spaced grid of points over the sphere (rows of latitude, columns spaced so the
    /// dots are about equally far apart everywhere), as unit vectors with a land flag.
    /// y is up (north pole at y = 1); longitude 0 faces +z.
    public struct Dot: Sendable, Equatable {
        public let x: Double, y: Double, z: Double
        public let land: Bool
    }

    public static func dots(spacing: Double = 2.4) -> [Dot] {
        var out: [Dot] = []
        var lat = -90 + spacing / 2
        while lat < 90 {
            let r = cos(lat * .pi / 180)
            let n = max(1, Int((360 * r / spacing).rounded()))
            for k in 0..<n {
                let lon = -180 + (Double(k) + 0.5) * 360 / Double(n)
                let (la, lo) = (lat * .pi / 180, lon * .pi / 180)
                out.append(Dot(x: cos(la) * sin(lo), y: sin(la), z: cos(la) * cos(lo), land: isLand(lon: lon, lat: lat)))
            }
            lat += spacing
        }
        return out
    }
